"""Research notes: saved passages, saved AI explanations and personal notes, plus export."""

from __future__ import annotations

import re
from dataclasses import asdict, dataclass, field

from .utils import new_id, now_iso

NOTE_KINDS = {
    "personal": "Personal note",
    "passage": "Saved passage",
    "ai": "AI explanation",
}


@dataclass
class Note:
    paper_id: str
    paper_title: str
    kind: str  # personal | passage | ai
    content: str
    page: int | None = None
    source_text: str = ""  # the original selected passage, kept verbatim
    mode: str = ""  # reading mode for AI notes
    model: str = ""  # model that produced an AI note
    tags: list[str] = field(default_factory=list)
    id: str = field(default_factory=lambda: new_id("n_"))
    created_at: str = field(default_factory=now_iso)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "Note":
        known = {f for f in cls.__dataclass_fields__}
        clean = {k: v for k, v in data.items() if k in known}
        clean.setdefault("tags", [])
        return cls(**clean)


def parse_tags(raw: str | list[str] | None) -> list[str]:
    if not raw:
        return []
    items = raw if isinstance(raw, list) else re.split(r"[,;#\n]+", raw)
    seen: list[str] = []
    for item in items:
        tag = re.sub(r"\s+", "-", str(item).strip().lower())[:40]
        if tag and tag not in seen:
            seen.append(tag)
    return seen[:20]


def make_note(paper_id: str, paper_title: str, kind: str, content: str, **kwargs) -> dict:
    if kind not in NOTE_KINDS:
        raise ValueError(f"Unknown note kind: {kind}")
    content = (content or "").strip()
    source = (kwargs.get("source_text") or "").strip()
    if not content and not source:
        raise ValueError("A note needs some content.")
    kwargs["tags"] = parse_tags(kwargs.get("tags"))
    return Note(paper_id=paper_id, paper_title=paper_title, kind=kind, content=content, **kwargs).to_dict()


def search_notes(
    notes: list[dict], query: str = "", paper_id: str | None = None, kinds: list[str] | None = None, tags: list[str] | None = None
) -> list[dict]:
    query = (query or "").strip().lower()
    out = []
    for n in notes:
        if paper_id and n.get("paper_id") != paper_id:
            continue
        if kinds and n.get("kind") not in kinds:
            continue
        if tags and not set(tags) & set(n.get("tags", [])):
            continue
        if query:
            haystack = " ".join(
                [n.get("content", ""), n.get("source_text", ""), n.get("paper_title", ""), " ".join(n.get("tags", []))]
            ).lower()
            if not all(term in haystack for term in query.split()):
                continue
        out.append(n)
    return sorted(out, key=lambda n: n.get("created_at", ""), reverse=True)


def all_tags(notes: list[dict]) -> list[str]:
    return sorted({t for n in notes for t in n.get("tags", [])})


def _page_label(note: dict) -> str:
    return f"p. {note['page']}" if note.get("page") else "page not recorded"


def export_markdown(notes: list[dict], title: str = "Readray notes") -> str:
    lines = [f"# {title}", "", f"_Exported {now_iso()} · {len(notes)} note(s)._", ""]
    lines.append("> Notes marked **AI explanation** were generated by an AI model and may contain errors. "
                 "Verify them against the original paper.")
    lines.append("")
    by_paper: dict[str, list[dict]] = {}
    for n in notes:
        by_paper.setdefault(n.get("paper_title") or "Untitled paper", []).append(n)
    for paper_title, items in by_paper.items():
        lines += [f"## {paper_title}", ""]
        for n in sorted(items, key=lambda x: (x.get("page") or 0, x.get("created_at", ""))):
            kind = NOTE_KINDS.get(n.get("kind", ""), n.get("kind", ""))
            extra = f" · mode: {n['mode']}" if n.get("mode") else ""
            extra += f" · model: {n['model']}" if n.get("model") else ""
            lines.append(f"### {kind} — {_page_label(n)}{extra}")
            if n.get("tags"):
                lines.append("Tags: " + ", ".join(f"`{t}`" for t in n["tags"]))
            lines.append("")
            if n.get("source_text"):
                lines += ["**Original passage:**", ""] + [f"> {ln}" if ln else ">" for ln in n["source_text"].splitlines()] + [""]
            if n.get("content"):
                if n.get("kind") == "ai":
                    lines += ["**AI-generated explanation (unverified):**", ""]
                elif n.get("kind") == "personal":
                    lines += ["**My note:**", ""]
                lines += [n["content"], ""]
            lines += [f"_Saved {n.get('created_at', '')}_", "", "---", ""]
    return "\n".join(lines).rstrip() + "\n"


def export_txt(notes: list[dict], title: str = "Readray notes") -> str:
    out = [title.upper(), f"Exported {now_iso()} - {len(notes)} note(s)",
           "AI explanations were generated by an AI model and may contain errors.", ""]
    for n in sorted(notes, key=lambda x: (x.get("paper_title", ""), x.get("page") or 0)):
        out.append("=" * 72)
        out.append(f"{NOTE_KINDS.get(n.get('kind', ''), n.get('kind', ''))} | {n.get('paper_title', '')} | {_page_label(n)}")
        if n.get("tags"):
            out.append("Tags: " + ", ".join(n["tags"]))
        if n.get("source_text"):
            out += ["", "ORIGINAL PASSAGE:", n["source_text"]]
        if n.get("content"):
            label = {"ai": "AI-GENERATED EXPLANATION (UNVERIFIED):", "personal": "MY NOTE:"}.get(n.get("kind", ""), "")
            out += ["", label, n["content"]] if label else ["", n["content"]]
        out.append("")
    return "\n".join(out).rstrip() + "\n"
